class TestCheckDockerComposeAvailable:
    """Tests for check_docker_compose_available function."""

    @patch("treemux.compose.subprocess.run")
    def test_available(self, mock_run):
        """docker composeが利用可能な場合はTrueを返す"""
        mock_run.return_value = MagicMock(returncode=0)

        assert check_docker_compose_available() is True

        cmd = mock_run.call_args[0][0]
        assert cmd == ["docker", "compose", "version"]

    @patch("treemux.compose.subprocess.run")
    def test_not_available(self, mock_run):
        """コマンドが失敗した場合はFalseを返す"""
        mock_run.return_value = MagicMock(returncode=1)

        assert check_docker_compose_available() is False

    @patch("treemux.compose.subprocess.run")
    def test_not_found(self, mock_run):
        """dockerが見つからない場合はFalseを返す"""
        mock_run.side_effect = FileNotFoundError()

        assert check_docker_compose_available() is False


class TestOverrideFileHelpers:
    """Tests for override file helper functions."""

    def test_get_override_file_path(self, project_root: Path):
        """正しいパスを返す"""
        result = get_override_file_path(project_root)
        assert result == project_root / OVERRIDE_FILE

    def test_override_file_exists_true(
        self, project_root: Path, sample_treemux_config: TreemuxConfig
    ):
        """ファイルが存在する場合はTrueを返す"""
        write_override_file(project_root, sample_treemux_config)
        assert override_file_exists(project_root) is True

    def test_override_file_exists_false(self, project_root: Path):
        """ファイルが存在しない場合はFalseを返す"""
        assert override_file_exists(project_root) is False
