def check_docker_compose_available() -> bool:
    """docker composeが利用可能か確認

    Returns:
        利用可能ならTrue
    """
    try:
        result = subprocess.run(
            ["docker", "compose", "version"],
            capture_output=True,
            text=True,
        )
        return result.returncode == 0
    except FileNotFoundError:
        return False


def get_override_file_path(project_root: Path) -> Path:
    """オーバーライドファイルのパスを取得"""
    return project_root / OVERRIDE_FILE


def override_file_exists(project_root: Path) -> bool:
    """オーバーライドファイルが存在するか確認"""
    return get_override_file_path(project_root).exists()
